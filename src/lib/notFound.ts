/**
 * Normalise a URL or path to a comparable `pathname`.
 *
 * Mirrors the reference's `zu`: undo the `hxxps://` / `[.]` defanging, strip a
 * scheme and host, drop the query and hash, and trim a trailing slash.
 */
export function normalisePath(value: string | null | undefined): string {
  if (!value) return '';
  let path = value.trim().toLowerCase();
  path = path.replace(/^hxxps:\/\//i, 'https://').replace(/^hxxp:\/\//i, 'http://');
  path = path.replace(/\[\.\]/g, '.');
  if (path.startsWith('http://') || path.startsWith('https://') || path.startsWith('//')) {
    try {
      path = new URL(path.startsWith('//') ? `https:${path}` : path).pathname;
    } catch {
      path = path.replace(/^[a-z]+:\/\/[^/]+/, '');
    }
  } else if (!path.startsWith('/') && path.includes('/')) {
    const slash = path.indexOf('/');
    const head = path.substring(0, slash);
    if (head.includes('.') || head.includes(':')) path = path.substring(slash);
  }
  path = path.split('?')[0].split('#')[0];
  if (path.length > 1 && path.endsWith('/')) path = path.replace(/\/+$/, '');
  if (path && !path.startsWith('/')) path = `/${path}`;
  return path;
}

/** The set of paths, in normalised form, derived once from the raw list. */
const NORMALISED = new Set(Array.from(NOT_FOUND_PATHS, normalisePath).filter(Boolean));

/**
 * Whether a path is on the known-404 list.
 *
 * `host` mirrors the reference's `Bu`: when the caller passes the *current*
 * host the check only applies on frameXTV's own domain (the list is keyed to
 * that site's URLs). The reference leaves `host` undefined for the
 * path-only call site, which is why this is optional.
 */
export function isNotFoundPath(value: string | null | undefined, host?: string | null): boolean {
  if (!value) return false;
  const path = normalisePath(value);
  if (!path) return false;
  if (host !== undefined && !isOwnHost(host)) return false;
  return NORMALISED.has(path);
}

/** Whether `host` is one of the reference's own origins (or empty). */
export function isOwnHost(host: string | null | undefined): boolean {
  const value = (host ?? '').toLowerCase().trim();
  if (!value) return true;
  return value === 'framextv.tech' || value === 'www.framextv.tech' || value.endsWith('.framextv.tech');
}
